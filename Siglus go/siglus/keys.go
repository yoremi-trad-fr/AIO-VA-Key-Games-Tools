func displayGameKeyName(name string) string {
	if display, ok := gameKeyDisplayNames[name]; ok {
		return display
	}
	return name
}

func presentedGameKey(gk GameKey) GameKey {
	gk.Name = displayGameKeyName(gk.Name)
	return gk
}

